def write_files(workspace: Path, file_map: dict[str, str], *, force: bool, dry_run: bool) -> None:
    for relative in file_map:
        target = workspace / relative
        if target.exists() and not force:
            raise SystemExit(f"refusing to overwrite existing file without --force: {target}")

    for relative, content in sorted(file_map.items()):
        target = workspace / relative
        if dry_run:
            print(target)
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        if relative in MANAGED_EXECUTABLES:
            target.chmod(target.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def write_email_env(workspace: Path, content: str, *, dry_run: bool) -> None:
    target = workspace / ".codex_monitor" / "email.env"
    if dry_run:
        print(target)
        return
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")
    target.chmod(0o600)


