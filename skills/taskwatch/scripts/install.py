def workspace_local_install_supported() -> bool:
    return os.name != "nt" or os.environ.get("TASKWATCH_ALLOW_WINDOWS_WORKSPACE_SCAFFOLD") == "1"


def resolve_scaffold_root(args: argparse.Namespace, workspace: Path) -> Path:
    if args.job_dir:
        return Path(args.job_dir).expanduser().resolve()
    if args.central:
        codex_home = Path(os.environ.get("CODEX_HOME", Path.home() / ".codex")).expanduser()
        return codex_home / "taskwatch" / "jobs" / args.systemd_basename
    return workspace


def uninstall_scaffold(scaffold_root: Path, *, purge: bool, dry_run: bool, allow_root_removal: bool) -> None:
    if not scaffold_root.exists():
        raise SystemExit(f"nothing to uninstall; scaffold root missing: {scaffold_root}")

    monitor_dir = scaffold_root / ".codex_monitor"
    timer_script = monitor_dir / "scripts" / "uninstall_systemd_timer.sh"
    if not dry_run and timer_script.exists() and os.name != "nt" and shutil.which("systemctl"):
        subprocess.run(["bash", str(timer_script)], check=False)

    removed = 0
    for relative in MANAGED_FILES:
        target = scaffold_root / relative
        if not target.exists():
            continue
        if dry_run:
            print(f"[dry-run] would remove {target}")
        else:
            target.unlink()
        removed += 1

    preserved = [
        str(monitor_dir / name)
        for name in ("email.env", "reports", "snapshots", "state")
        if (monitor_dir / name).exists()
    ]
    if purge and monitor_dir.exists():
        if dry_run:
            print(f"[dry-run] would remove {monitor_dir} recursively")
        else:
            shutil.rmtree(monitor_dir, ignore_errors=True)
        preserved = []
    elif not dry_run:
        for relative in (".codex_monitor/scripts", ".codex_monitor/reports", ".codex_monitor/snapshots", ".codex_monitor/state", ".codex_monitor"):
            candidate = scaffold_root / relative
            if candidate.is_dir():
                try:
                    candidate.rmdir()
                except OSError:
                    pass

    if allow_root_removal and not dry_run and scaffold_root.is_dir():
        try:
            scaffold_root.rmdir()
        except OSError:
            pass

    print(f"[summary] uninstall {'previewed' if dry_run else 'finished'}: {removed} managed file(s) under {scaffold_root}")
    if preserved:
        print("[summary] preserved runtime files (use --purge to delete):")
        for path in preserved:
            print(f"  {path}")
    if os.name == "nt" or not shutil.which("systemctl"):
        print("[summary] systemd timer not touched on this host; run uninstall_systemd_timer.sh on the Linux host if the timer was installed")


def main() -> int:
    args = parse_args()
    if args.purge and not args.uninstall:
        raise SystemExit("--purge requires --uninstall")
    validate_layout_inputs(args)
    if not workspace_local_install_supported() and not args.uninstall:
        raise SystemExit(
            "TaskWatch workspace-local monitor is Linux only. "
            "On Windows, install only the global goal Stop hook with "
            "scripts/install_global_hook.py."
        )

    workspace = Path(args.workspace).expanduser().resolve()
    scaffold_root = resolve_scaffold_root(args, workspace)

    if args.uninstall:
        uninstall_scaffold(
            scaffold_root,
            purge=args.purge,
            dry_run=args.dry_run,
            allow_root_removal=scaffold_root != workspace,
        )
        return 0

    if not workspace.exists() or not workspace.is_dir():
        raise SystemExit(f"workspace is missing or not a directory: {workspace}")

    _, resolved_smtp, email_env = validate_install_inputs(args)

    artifact_dirs = tuple(args.artifact_dirs or ["logs", "outputs", "reports", "results", "artifacts"])
    config = InstallConfig(
        workspace=workspace,
        label=args.label,
        systemd_basename=args.systemd_basename,
        job_service=args.job_service,
        primary_log=args.primary_log,
        progress_log=args.progress_log,
        artifact_dirs=artifact_dirs,
        process_grep=args.process_grep,
        codex_model=args.codex_model,
        run_command=args.run_command,
        goal_mode=args.goal_mode,
    )
    file_map = build_file_map(config)
    write_files(scaffold_root, file_map, force=args.force, dry_run=args.dry_run)
    if not args.dry_run:
        (scaffold_root / ".codex_monitor" / "state").chmod(0o700)

    if email_env is not None:
        write_email_env(scaffold_root, email_env, dry_run=args.dry_run)

    if not args.dry_run:
        print_install_summary(
            scaffold_root,
            workspace,
            config,
            email_enabled=resolved_smtp is not None,
            smtp_host=resolved_smtp[0] if resolved_smtp else None,
            smtp_port=resolved_smtp[1] if resolved_smtp else None,
            smtp_security=resolved_smtp[2] if resolved_smtp else None,
        )
    return 0


