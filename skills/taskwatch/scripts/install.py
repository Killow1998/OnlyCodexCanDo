README_TEMPLATE = """# @@LABEL@@ Codex Monitor

This folder contains a workspace-local Codex monitor for any long-running Linux job that should be watched over time and summarized into friendly reports.

Typical targets:

- model training;
- evaluation or benchmark runs;
- long goal-mode or batch Codex jobs;
- offline data processing with meaningful logs and artifacts.

The monitor provides:

- hourly read-only markdown reports;
- final completion or failure summaries;
- goal-mode terminal emails for `complete`, `blocked`, and `usageLimited`;
- optional SMTP email notification for the final result;
- a systemd user timer for periodic inspection;
- a wrapper that records start time, end time, exit code, and the local run log.

## Quick Start

1. Edit the actual job command:

```bash
.codex_monitor/run_command.sh
```

2. Review monitor config:

```bash
.codex_monitor/monitor.env
```

3. If email is wanted and `.codex_monitor/email.env` does not already exist:

```bash
cp .codex_monitor/email.env.example .codex_monitor/email.env
```

4. Start the long-running job through the wrapper:

```bash
./run_with_monitor.sh
```

Compatibility alias:

```bash
./run_train_with_monitor.sh
```

5. Generate one manual hourly report without sending mail:

```bash
CODEX_MONITOR_SKIP_EMAIL=1 .codex_monitor/scripts/hourly_check.sh
```

6. Install or remove the user timer:

```bash
.codex_monitor/scripts/install_systemd_timer.sh
.codex_monitor/scripts/uninstall_systemd_timer.sh
```

## Notes

- Linux only. The timer installer targets `systemd --user`.
- Codex reporting is read-only.
- Final email is sent only when the run is marked done or failed.
- For Codex goal runs, install with `--goal-mode` so the final email can distinguish `complete`, `blocked`, and `usageLimited`.
- Reports, snapshots, state files, and SMTP secrets should stay local and untracked.
"""


